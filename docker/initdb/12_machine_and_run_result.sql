-- machine     : kosunun yapildigi bilgisayar (uygulama ilk kosuda kendisi ekler,
--               bkz. persistence.MachineInfo). solving_checkpoint ve solver_run
--               satirlari machine_id tasir.
-- run_result  : her hesaplama icin TEK satir sonuc istatistigi (makale icin).
--               Anahtar: grid + algoritma + checkpoint_version + tarama + kayit modu.
--               Restart/resume'lar ayni satira toplanir.
-- run_result_square : kare kare dokum (cozum, carpan, katki, sure, adim).
-- refresh_run_result(grid_map_id DEFAULT NULL) : iki tabloyu solving_checkpoint /
--               solver_run / flat / trie verisinden hesaplar.
--               status COMPLETED olan satirlarda SADECE bos (NULL) alanlari doldurur
--               (elle girilen deger ve notlar ezilmez); digerlerinde yeniden hesaplar.
--               Checkpoint hesaplamalari uygulama tum kareleri bitirince COMPLETED olur;
--               flat/trie durumu solver_run.status'tan gelir.
--
-- Var olan DB'ye elle uygula (cozucu durmusken):
--   docker exec -i dev-postgres psql -U pathexplorer -d pathexplorer < docker/initdb/12_machine_and_run_result.sql

BEGIN;

CREATE TABLE IF NOT EXISTS machine (
    id              smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostname        text     NOT NULL,
    model           text,               -- orn. "Dell Inc. OptiPlex SFF Plus 7010"
    cpu_model       text,               -- orn. "13th Gen Intel(R) Core(TM) i7-13700"
    cpu_cores       smallint,           -- fiziksel cekirdek
    cpu_threads     smallint,           -- mantiksal islemci
    cpu_base_ghz    numeric(4,2),
    cpu_max_ghz     numeric(4,2),       -- turbo; Windows'tan okunamiyor, elle doldur
    cpu_l3_mb       smallint,
    ram_gb          smallint,
    ram_type        text,               -- DDR4 / DDR5
    ram_mts         smallint,           -- calisan hiz (ConfiguredClockSpeed)
    ram_modules     smallint,           -- takili modul sayisi (1 = tek kanal)
    disk            text,
    os              text     NOT NULL,
    java            text     NOT NULL,  -- vendor + surum
    jvm_max_heap_mb integer,
    gc              text,
    db_version      text,
    power_plan      text,
    notes           text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    -- Ayni bilgisayarda RAM/OS/Java degisirse sureler degisir -> yeni satir.
    CONSTRAINT machine_identity_key UNIQUE NULLS NOT DISTINCT (hostname, cpu_model, ram_gb, os, java)
);

ALTER TABLE solving_checkpoint ADD COLUMN IF NOT EXISTS machine_id smallint REFERENCES machine(id);
ALTER TABLE solver_run         ADD COLUMN IF NOT EXISTS machine_id smallint REFERENCES machine(id);
COMMENT ON COLUMN solving_checkpoint.machine_id IS 'satiri yazan bilgisayar (machine)';
COMMENT ON COLUMN solver_run.machine_id IS 'kosunun yapildigi bilgisayar (machine)';

CREATE TABLE IF NOT EXISTS run_result (
    id                  serial   PRIMARY KEY,
    -- kimlik
    grid_map_id         smallint NOT NULL REFERENCES grid_map(id),
    algorithm_id        smallint NOT NULL REFERENCES solving_algorithm(id),
    checkpoint_version  smallint REFERENCES checkpoint_version(id),   -- flat/trie: NULL
    run_map_type_id     smallint NOT NULL REFERENCES run_map_type(id),
    save_mode           varchar(10) NOT NULL,                        -- checkpoint | flat | trie
    solver_run_id       bigint REFERENCES solver_run(id) ON DELETE SET NULL,  -- flat/trie: kaynak kosu
    machine_id          smallint REFERENCES machine(id),             -- birden fazla PC ise NULL
    status              varchar(10) NOT NULL DEFAULT 'RUNNING',      -- RUNNING | COMPLETED | ABORTED
    -- sonuc
    visited_solutions   bigint,     -- gezilen baslangic karelerinden bulunan cozum
    total_solutions     bigint,     -- tum tahta (UNIQUE ise carpanlarla)
    total_steps         bigint,     -- round_counter (ileri + geri hamle)
    back_steps          bigint,
    dummy_back_steps    bigint,
    -- zaman
    started_at          timestamptz,
    finished_at         timestamptz,
    wall_time           interval,   -- finished_at - started_at (duvar saati)
    solve_time          interval,   -- saf cozme suresi: checkpoint'te Σ elapsed, flat/trie'de wall_time
    idle_time           interval,   -- wall_time - solve_time (kapali kalma, restart, kayit)
    unmeasured_rows     integer,    -- elapsed'i bilinmeyen checkpoint satiri
    elapsed_min         interval,   -- iki checkpoint arasi en kisa / en uzun sure
    elapsed_max         interval,
    -- kesinti / kayit
    run_count           integer,    -- yazan process sayisi
    restart_count       integer,
    checkpoint_interval integer,
    checkpoint_rows     integer,
    -- hiz (solve_time'a gore)
    solutions_per_sec   numeric(14,2),
    steps_per_sec       numeric(16,2),
    computed_at         timestamptz,
    notes               text,
    CONSTRAINT run_result_identity_key UNIQUE NULLS NOT DISTINCT
        (grid_map_id, algorithm_id, checkpoint_version, run_map_type_id, save_mode)
);

CREATE TABLE IF NOT EXISTS run_result_square (
    run_result_id integer  NOT NULL REFERENCES run_result(id) ON DELETE CASCADE,
    x             smallint NOT NULL,
    y             smallint NOT NULL,
    multiplier    smallint NOT NULL,   -- ALL: 1, UNIQUE: simetri carpani
    solutions     bigint,
    contribution  bigint,              -- solutions * multiplier
    solve_time    interval,            -- sadece checkpoint
    steps         bigint,              -- sadece checkpoint
    PRIMARY KEY (run_result_id, x, y)
);

-- Kare grid'de temel bolge karesinin simetri carpani (bkz. unique-area-calculation.md).
CREATE OR REPLACE FUNCTION grid_square_multiplier(n int, x int, y int) RETURNS int
LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE
        WHEN n % 2 = 1 AND x = (n - 1) / 2 AND y = (n - 1) / 2 THEN 1
        WHEN x = y OR (n % 2 = 1 AND (x = (n - 1) / 2 OR y = (n - 1) / 2)) THEN 4
        ELSE 8
    END
$$;

CREATE OR REPLACE FUNCTION refresh_run_result(p_grid_map_id smallint DEFAULT NULL) RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE
    rec     record;
    v_rid   integer;
    v_count integer := 0;
BEGIN
    DROP TABLE IF EXISTS rr_calc, rr_sq;
    CREATE TEMP TABLE rr_calc ON COMMIT DROP AS SELECT * FROM run_result WITH NO DATA;
    CREATE TEMP TABLE rr_sq (
        grid_map_id smallint, algorithm_id smallint, checkpoint_version smallint,
        run_map_type_id smallint, save_mode varchar(10),
        x smallint, y smallint, multiplier smallint, solutions bigint,
        contribution bigint, solve_time interval, steps bigint) ON COMMIT DROP;

    -- ---------- checkpoint hesaplamalari ----------
    INSERT INTO rr_sq
    WITH c AS (
        SELECT c.grid_map_id, c.algorithm_id, c.checkpoint_version, c.run_map_type_id,
               coalesce(split_part(c.first_location, '-', 1)::int, get_byte(c.path, 0) / g.col_size) AS x,
               coalesce(split_part(c.first_location, '-', 2)::int, get_byte(c.path, 0) % g.col_size) AS y,
               c.solution_index, c.round_counter, c.elapsed, g.row_size, g.col_size
        FROM solving_checkpoint c JOIN grid_map g ON g.id = c.grid_map_id
        WHERE p_grid_map_id IS NULL OR c.grid_map_id = p_grid_map_id
    ), sq AS (
        SELECT grid_map_id, algorithm_id, checkpoint_version, run_map_type_id, x, y,
               max(row_size) grid_n, bool_and(row_size = col_size) is_square,
               max(solution_index) last_si, max(round_counter) last_rc, sum(elapsed) st
        FROM c GROUP BY 1, 2, 3, 4, 5, 6
    ), d AS (
        SELECT *, last_si - coalesce(lag(last_si) OVER w, 0) AS sols,
                  last_rc - coalesce(lag(last_rc) OVER w, 0) AS stp
        FROM sq WINDOW w AS (PARTITION BY grid_map_id, algorithm_id, checkpoint_version, run_map_type_id
                             ORDER BY last_si)
    )
    SELECT grid_map_id, algorithm_id, checkpoint_version, run_map_type_id, 'checkpoint', x, y,
           m, sols, sols * m, st, stp
    FROM d, LATERAL (SELECT CASE WHEN run_map_type_id = 1 OR NOT is_square THEN 1
                                 ELSE grid_square_multiplier(grid_n, x, y) END AS m) mm;

    INSERT INTO rr_calc (grid_map_id, algorithm_id, checkpoint_version, run_map_type_id, save_mode,
                         machine_id, status, visited_solutions, total_steps, back_steps, dummy_back_steps,
                         started_at, finished_at, wall_time, solve_time, idle_time, unmeasured_rows,
                         elapsed_min, elapsed_max, run_count, restart_count, checkpoint_interval,
                         checkpoint_rows, computed_at)
    SELECT k.grid_map_id, k.algorithm_id, k.checkpoint_version, k.run_map_type_id, 'checkpoint',
           CASE WHEN count(DISTINCT k.machine_id) = 1 THEN max(k.machine_id) END,
           'RUNNING',
           max(k.solution_index),
           (array_agg(k.round_counter ORDER BY k.solution_index DESC))[1],
           (array_agg(k.total_back_steps ORDER BY k.solution_index DESC))[1],
           (array_agg(k.dummy_back_steps ORDER BY k.solution_index DESC))[1],
           min(k.created_at), max(k.created_at), justify_hours(max(k.created_at) - min(k.created_at)),
           sum(k.elapsed),
           make_interval(secs => extract(epoch FROM max(k.created_at) - min(k.created_at)) - extract(epoch FROM sum(k.elapsed))),
           count(*) FILTER (WHERE k.elapsed IS NULL),
           min(k.elapsed) FILTER (WHERE k.solution_index % k.interval_size = 0),
           max(k.elapsed) FILTER (WHERE k.solution_index % k.interval_size = 0),
           count(DISTINCT k.solving_run_id), count(DISTINCT k.solving_run_id) - 1,
           max(k.interval_size), count(*), now()
    FROM solving_checkpoint k
    WHERE p_grid_map_id IS NULL OR k.grid_map_id = p_grid_map_id
    GROUP BY 1, 2, 3, 4;

    -- ---------- flat / trie: her anahtar icin en son solver_run ----------
    INSERT INTO rr_calc (grid_map_id, algorithm_id, checkpoint_version, run_map_type_id, save_mode,
                         machine_id, status, visited_solutions, total_steps, back_steps, dummy_back_steps,
                         started_at, finished_at, wall_time, solve_time, idle_time, run_count, restart_count,
                         computed_at, solver_run_id)
    SELECT DISTINCT ON (s.grid_map_id, a.id, s.run_map_type_id, s.save_mode)
           s.grid_map_id, a.id, NULL, s.run_map_type_id, s.save_mode, s.machine_id, s.status,
           s.total_solved, s.round_counter, s.total_back_steps, s.dummy_back_steps,
           s.started_at, s.finished_at, s.finished_at - s.started_at,
           coalesce(make_interval(secs => s.elapsed_ms / 1000.0), s.finished_at - s.started_at),
           CASE WHEN s.elapsed_ms IS NOT NULL
                THEN make_interval(secs => extract(epoch FROM s.finished_at - s.started_at) - s.elapsed_ms / 1000.0)
                ELSE interval '0' END,
           1, 0, now(), s.id
    FROM solver_run s JOIN solving_algorithm a ON a.code = s.algorithm
    WHERE s.save_mode IN ('flat', 'trie') AND s.grid_map_id IS NOT NULL
      AND (p_grid_map_id IS NULL OR s.grid_map_id = p_grid_map_id)
    ORDER BY s.grid_map_id, a.id, s.run_map_type_id, s.save_mode, s.id DESC;

    -- flat: baslangic karesine gore; trie: kok dugumleri (step_no = 1)
    INSERT INTO rr_sq
    SELECT r.grid_map_id, r.algorithm_id, NULL::smallint, r.run_map_type_id, 'flat', p.start_x, p.start_y,
           mm.m, count(*), count(*) * mm.m, NULL::interval, NULL::bigint
    FROM rr_calc r
    JOIN path_explorer_solution p ON p.grid_map_id = r.grid_map_id
                                 AND p.solver_run_id = r.solver_run_id
    JOIN grid_map g ON g.id = r.grid_map_id
    CROSS JOIN LATERAL (SELECT CASE WHEN r.run_map_type_id = 1 OR g.row_size <> g.col_size THEN 1
                                    ELSE grid_square_multiplier(g.row_size, p.start_x, p.start_y) END AS m) mm
    WHERE r.save_mode = 'flat'
    GROUP BY 1, 2, 3, 4, 5, 6, 7, 8;

    INSERT INTO rr_sq
    SELECT r.grid_map_id, r.algorithm_id, NULL::smallint, r.run_map_type_id, 'trie', t.x, t.y,
           mm.m, t.subtree_solution_count, t.subtree_solution_count * mm.m, NULL::interval, NULL::bigint
    FROM rr_calc r
    JOIN solution_step t ON t.grid_map_id = r.grid_map_id AND t.algorithm_id = r.algorithm_id AND t.step_no = 1
    JOIN grid_map g ON g.id = r.grid_map_id
    CROSS JOIN LATERAL (SELECT CASE WHEN r.run_map_type_id = 1 OR g.row_size <> g.col_size THEN 1
                                    ELSE grid_square_multiplier(g.row_size, t.x, t.y) END AS m) mm
    WHERE r.save_mode = 'trie';

    -- ---------- tum tahta toplami + hiz ----------
    UPDATE rr_calc r SET
        total_solutions = CASE WHEN r.run_map_type_id = 1 THEN r.visited_solutions
                               ELSE (SELECT sum(q.contribution) FROM rr_sq q
                                      WHERE q.grid_map_id = r.grid_map_id AND q.algorithm_id = r.algorithm_id
                                        AND q.checkpoint_version IS NOT DISTINCT FROM r.checkpoint_version
                                        AND q.run_map_type_id = r.run_map_type_id AND q.save_mode = r.save_mode) END,
        solutions_per_sec = round(r.visited_solutions / nullif(extract(epoch FROM r.solve_time), 0), 2),
        steps_per_sec     = round(r.total_steps / nullif(extract(epoch FROM r.solve_time), 0), 2);

    -- ---------- upsert: COMPLETED satirda sadece bos alanlar dolar ----------
    FOR rec IN SELECT * FROM rr_calc LOOP
        INSERT INTO run_result AS t (grid_map_id, algorithm_id, checkpoint_version, run_map_type_id, save_mode,
               solver_run_id,                machine_id, status, visited_solutions, total_solutions, total_steps, back_steps, dummy_back_steps,
               started_at, finished_at, wall_time, solve_time, idle_time, unmeasured_rows, elapsed_min, elapsed_max,
               run_count, restart_count, checkpoint_interval, checkpoint_rows, solutions_per_sec, steps_per_sec,
               computed_at, notes)
        VALUES (rec.grid_map_id, rec.algorithm_id, rec.checkpoint_version, rec.run_map_type_id, rec.save_mode,
               rec.solver_run_id,                rec.machine_id, rec.status, rec.visited_solutions, rec.total_solutions, rec.total_steps, rec.back_steps,
               rec.dummy_back_steps, rec.started_at, rec.finished_at, rec.wall_time, rec.solve_time, rec.idle_time,
               rec.unmeasured_rows, rec.elapsed_min, rec.elapsed_max, rec.run_count, rec.restart_count,
               rec.checkpoint_interval, rec.checkpoint_rows, rec.solutions_per_sec, rec.steps_per_sec, rec.computed_at, rec.notes)
        ON CONFLICT ON CONSTRAINT run_result_identity_key DO UPDATE SET
            solver_run_id       = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.solver_run_id, EXCLUDED.solver_run_id) ELSE EXCLUDED.solver_run_id END,
            machine_id          = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.machine_id, EXCLUDED.machine_id) ELSE EXCLUDED.machine_id END,
            status              = CASE WHEN t.status = 'COMPLETED' THEN t.status ELSE EXCLUDED.status END,
            visited_solutions   = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.visited_solutions, EXCLUDED.visited_solutions) ELSE EXCLUDED.visited_solutions END,
            total_solutions     = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.total_solutions, EXCLUDED.total_solutions) ELSE EXCLUDED.total_solutions END,
            total_steps         = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.total_steps, EXCLUDED.total_steps) ELSE EXCLUDED.total_steps END,
            back_steps          = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.back_steps, EXCLUDED.back_steps) ELSE EXCLUDED.back_steps END,
            dummy_back_steps    = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.dummy_back_steps, EXCLUDED.dummy_back_steps) ELSE EXCLUDED.dummy_back_steps END,
            started_at          = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.started_at, EXCLUDED.started_at) ELSE EXCLUDED.started_at END,
            finished_at         = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.finished_at, EXCLUDED.finished_at) ELSE EXCLUDED.finished_at END,
            wall_time           = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.wall_time, EXCLUDED.wall_time) ELSE EXCLUDED.wall_time END,
            solve_time          = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.solve_time, EXCLUDED.solve_time) ELSE EXCLUDED.solve_time END,
            idle_time           = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.idle_time, EXCLUDED.idle_time) ELSE EXCLUDED.idle_time END,
            unmeasured_rows     = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.unmeasured_rows, EXCLUDED.unmeasured_rows) ELSE EXCLUDED.unmeasured_rows END,
            elapsed_min         = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.elapsed_min, EXCLUDED.elapsed_min) ELSE EXCLUDED.elapsed_min END,
            elapsed_max         = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.elapsed_max, EXCLUDED.elapsed_max) ELSE EXCLUDED.elapsed_max END,
            run_count           = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.run_count, EXCLUDED.run_count) ELSE EXCLUDED.run_count END,
            restart_count       = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.restart_count, EXCLUDED.restart_count) ELSE EXCLUDED.restart_count END,
            checkpoint_interval = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.checkpoint_interval, EXCLUDED.checkpoint_interval) ELSE EXCLUDED.checkpoint_interval END,
            checkpoint_rows     = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.checkpoint_rows, EXCLUDED.checkpoint_rows) ELSE EXCLUDED.checkpoint_rows END,
            solutions_per_sec   = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.solutions_per_sec, EXCLUDED.solutions_per_sec) ELSE EXCLUDED.solutions_per_sec END,
            steps_per_sec       = CASE WHEN t.status = 'COMPLETED' THEN coalesce(t.steps_per_sec, EXCLUDED.steps_per_sec) ELSE EXCLUDED.steps_per_sec END,
            computed_at         = now(),
            notes               = coalesce(t.notes, EXCLUDED.notes)
        RETURNING t.id INTO v_rid;

        INSERT INTO run_result_square AS s (run_result_id, x, y, multiplier, solutions, contribution, solve_time, steps)
        SELECT v_rid, q.x, q.y, q.multiplier, q.solutions, q.contribution, q.solve_time, q.steps
        FROM rr_sq q
        WHERE q.grid_map_id = rec.grid_map_id AND q.algorithm_id = rec.algorithm_id
          AND q.checkpoint_version IS NOT DISTINCT FROM rec.checkpoint_version
          AND q.run_map_type_id = rec.run_map_type_id AND q.save_mode = rec.save_mode
        ON CONFLICT (run_result_id, x, y) DO UPDATE SET
            multiplier   = EXCLUDED.multiplier,
            solutions    = CASE WHEN (SELECT status FROM run_result WHERE id = s.run_result_id) = 'COMPLETED'
                                THEN coalesce(s.solutions, EXCLUDED.solutions) ELSE EXCLUDED.solutions END,
            contribution = CASE WHEN (SELECT status FROM run_result WHERE id = s.run_result_id) = 'COMPLETED'
                                THEN coalesce(s.contribution, EXCLUDED.contribution) ELSE EXCLUDED.contribution END,
            solve_time   = CASE WHEN (SELECT status FROM run_result WHERE id = s.run_result_id) = 'COMPLETED'
                                THEN coalesce(s.solve_time, EXCLUDED.solve_time) ELSE EXCLUDED.solve_time END,
            steps        = CASE WHEN (SELECT status FROM run_result WHERE id = s.run_result_id) = 'COMPLETED'
                                THEN coalesce(s.steps, EXCLUDED.steps) ELSE EXCLUDED.steps END;
        v_count := v_count + 1;
    END LOOP;
    RETURN v_count;
END
$$;

COMMIT;
